#!/bin/bash
# ── run_membulk_benchmark.sh ─────────────────────────────────────────────
#
# A/B benchmark for the in-memory bulk index path vs the streaming path on a
# ~2000-file module workload.
#
#   Baseline (streaming):  CODESCOPE_FORCE_STREAMING=1 (always streaming)
#   New      (membulk):    default (in-memory bulk path for <= 2000 files)
#
# Reports wall time, peak RSS, and node/edge counts for both, proving the
# membulk path is faster AND produces identical graph data.
#
# Usage:
#   ./benchmarks/run_membulk_benchmark.sh [code_dir] [runs]
#
# Requires a built codescope binary (default: ./target/release/codescope).
# If code_dir is omitted, a synthetic 2000-file C++ workload is generated.
#
set -euo pipefail

CODESCOPE="${CODESCOPE:-./target/release/codescope}"
RUNS="${2:-3}"
WORK="${1:-}"

TMP_ROOT="$(mktemp -d)"
RESULTS="benchmarks/results/membulk_bench.md"
mkdir -p benchmarks/results

# ── Build (or accept) a ~2000-file workload ──────────────────────────────
if [ -z "$WORK" ]; then
    WORK="${TMP_ROOT}/workload"
    mkdir -p "$WORK"
    echo "  Generating 2000 synthetic C++ files in $WORK ..."
    for i in $(seq 1 2000); do
        cat > "$WORK/mod_${i}.cpp" <<-EOF
		int helper_${i}(int x) { return x * ${i}; }
		int compute_${i}(int a, int b) {
		    int s = helper_${i}(a);
		    int t = helper_${i}(b);
		    return s + t;
		}
		int run_${i}() { return compute_${i}(1, 2); }
		EOF
    done
fi

FILE_COUNT=$(find "$WORK" -type f | wc -l | tr -d ' ')

run_one() {
    local force_streaming="$1" label="$2"
    local db="${TMP_ROOT}/bench_${label}.db"
    rm -f "${db}"*
    local t0 rss_start rss_peak rss pid

    local env_prefix=""
    [ "$force_streaming" = "1" ] && env_prefix="CODESCOPE_FORCE_STREAMING=1"

    t0=$(date +%s)
    # Launch and sample peak RSS while it runs.
    ( CODESCOPE_INDEX_MODE=fast CODESCOPE_WORKERS=4 $env_prefix \
        "$CODESCOPE" worker "$db" "$WORK" "" "bench-${label}" 0 ) &
    pid=$!
    rss_peak=0
    while kill -0 "$pid" 2>/dev/null; do
        rss=$(ps -o rss= -p "$pid" 2>/dev/null | tr -d ' ')
        [ -n "$rss" ] && [ "$rss" -gt "$rss_peak" ] && rss_peak=$rss
        sleep 0.1
    done
    wait "$pid" 2>/dev/null || true
    local dur=$(( $(date +%s) - t0 ))

    local nodes edges
    nodes=$(sqlite3 "$db" "SELECT COUNT(*) FROM graph_nodes;" 2>/dev/null || echo 0)
    edges=$(sqlite3 "$db" "SELECT COUNT(*) FROM graph_edges;" 2>/dev/null || echo 0)
    # Convert RSS (KB) to MB.
    local rss_mb=$(( rss_peak / 1024 ))
    echo "${dur} ${rss_mb} ${nodes} ${edges}"
}

echo "  Workload: $FILE_COUNT files, $RUNS runs per mode"
echo "| Mode | Run | Wall(s) | PeakRSS(MB) | Nodes | Edges |" > "$RESULTS"
echo "|------|-----|---------|-------------|-------|-------|" >> "$RESULTS"

for mode in streaming membulk; do
    fs=0; [ "$mode" = "streaming" ] && fs=1
    for r in $(seq 1 "$RUNS"); do
        read dur rss nodes edges <<< "$(run_one "$fs" "${mode}_${r}")"
        printf "| %s | %s | %s | %s | %s | %s |\n" "$mode" "$r" "$dur" "$rss" "$nodes" "$edges" >> "$RESULTS"
    done
done

echo "" >> "$RESULTS"
echo "Generated by benchmarks/run_membulk_benchmark.sh" >> "$RESULTS"
cat "$RESULTS"

# Cleanup synthetic workload only.
[ -z "${1:-}" ] && rm -rf "$TMP_ROOT" || rm -rf "${TMP_ROOT}/bench_"*.db
echo "  Results written to $RESULTS"
